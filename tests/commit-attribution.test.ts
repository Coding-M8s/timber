import { expect, test } from "bun:test";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { execa } from "execa";
import { hasAIAttribution } from "../scripts/check-commit-attribution";
import { git, withRepository } from "./helpers/git";

const root = fileURLToPath(new URL("..", import.meta.url));
const checker = join(root, "scripts/check-commit-attribution.ts");

test("AI attribution rejects assistant identities while preserving human credits and feature descriptions", () => {
  for (const credit of [
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "co-authored-by: Codex <noreply@openai.com>",
    "Co-Authored-By: GitHub Copilot <copilot@github.com>",
    "Co-authored-by: Cursor <cursoragent@cursor.com>",
    "Co-authored-by: GPT-6.1 Sol <bot@example.invalid>",
    "Co-authored-by: Gemini [bot] <bot@example.invalid>",
    "Assisted-by: AI assistant <bot@example.invalid>",
    "Generated-by: Claude Code",
    "🤖 Generated with [Claude Code](https://example.invalid)",
    "Generated by GPT-6.1",
    "Generated with Codeium",
    "Generated with Amazon Q",
  ]) expect(hasAIAttribution("Implement feature\r\n\r\n" + credit)).toBe(true);
  for (const message of [
    "Add Claude and Codex tools to Arena",
    "Explain why AI coauthors are prohibited",
    "Fix bug\n\nCo-authored-by: Claude Smith <claude.smith@example.invalid>",
    "Fix bug\n\nCo-authored-by: Jane Doe <jane@openai.com>",
    "Signed-off-by: Jane Doe <jane@example.invalid>",
  ]) expect(hasAIAttribution(message)).toBe(false);
});

test("local commit hook rejects AI credit without changing refs or rewriting message; human credit succeeds", async () => {
  await withRepository(async primary => {
    const before = await git(primary, "rev-parse", "HEAD");
    const options = ["-c", `core.hooksPath=${join(root, ".githooks")}`, "-c", "user.name=Timber Test", "-c", "user.email=test@example.invalid"];
    const badMessage = "Fix bug\n\nCo-authored-by: Codex <noreply@openai.com>";
    const rejected = await execa("git", [...options, "commit", "--allow-empty", "-m", badMessage], { cwd: primary, reject: false });
    expect(rejected.exitCode).toBe(1);
    expect(rejected.stderr).toContain("prohibited");
    expect(await git(primary, "rev-parse", "HEAD")).toBe(before);
    expect(await readFile(join(primary, ".git/COMMIT_EDITMSG"), "utf8")).toContain(badMessage);
    const humanMessage = "Fix bug\n\nCo-authored-by: Jane Doe <jane@example.invalid>";
    await git(primary, ...options, "commit", "--allow-empty", "-m", humanMessage);
    expect(await git(primary, "log", "-1", "--format=%B")).toContain("Jane Doe");
  });
});

test("CI checks every introduced commit and reports hashes without dumping messages", async () => {
  await withRepository(async (primary, directory) => {
    const base = await git(primary, "rev-parse", "HEAD");
    const commit = async (message: string) => {
      await git(primary, "-c", "core.hooksPath=/dev/null", "-c", "user.name=Timber Test", "-c", "user.email=test@example.invalid", "commit", "--allow-empty", "-m", message);
      return git(primary, "rev-parse", "HEAD");
    };
    const bad = await commit("PRIVATE_SENTINEL\n\nCo-authored-by: Claude <noreply@anthropic.com>");
    const head = await commit("Add Claude model documentation");
    const event = join(directory, "event.json");
    await writeFile(event, JSON.stringify({ pull_request: { base: { sha: base }, head: { sha: head } } }));
    const rejected = await execa(process.execPath, ["--no-env-file", checker, "--event", event], { cwd: primary, reject: false });
    expect(rejected.exitCode).toBe(1);
    expect(rejected.stderr).toContain(bad.slice(0, 12));
    expect(rejected.stderr).not.toContain("PRIVATE_SENTINEL");
    await writeFile(event, JSON.stringify({ before: bad, after: head }));
    const accepted = await execa(process.execPath, ["--no-env-file", checker, "--event", event], { cwd: primary });
    expect(accepted.exitCode).toBe(0);
    await writeFile(event, JSON.stringify({ pull_request: { base: { sha: bad }, head: { sha: head }, body: "Generated with Claude Code" } }));
    const prCredit = await execa(process.execPath, ["--no-env-file", checker, "--event", event], { cwd: primary, reject: false });
    expect(prCredit.exitCode).toBe(1);
    expect(prCredit.stderr).toContain("PR descriptions");
    const tip = await execa(process.execPath, ["--no-env-file", checker], { cwd: primary });
    expect(tip.exitCode).toBe(0);
    const audit = await execa(process.execPath, ["--no-env-file", checker, "--all-history"], { cwd: primary, reject: false });
    expect(audit.exitCode).toBe(1);
    expect(audit.stderr).toContain(bad.slice(0, 12));
    // A new branch must not be rejected for credits already inherited from its default branch.
    await git(primary, "update-ref", "refs/remotes/origin/trunk", bad);
    await writeFile(event, JSON.stringify({ before: "0".repeat(40), after: head, ref: "refs/heads/feature", repository: { default_branch: "trunk" } }));
    const createdBranch = await execa(process.execPath, ["--no-env-file", checker, "--event", event], { cwd: primary });
    expect(createdBranch.exitCode).toBe(0);
  });
});
